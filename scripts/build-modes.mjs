/**
 * Maintainer tool: vendors every CodeMirror 5 mode and builds the language table
 * from what the packages actually register.
 *
 * Run after changing the vendored CodeMirror version:
 *   node scripts/build-modes.mjs
 *
 * The table is derived by executing each mode file, not by trusting mode/meta.js:
 * several packages register a different MIME than the metadata advertises
 * (Dart registers application/dart, not text/x-dart), and the simple-mode
 * packages only register anything once addon/mode/simple.js is present. Entries
 * whose package registers nothing are dropped and reported instead of being
 * shipped as highlighting that silently does nothing.
 */

import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

import { loadModes } from "./lib/codemirror-sandbox.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(here, "..");
const sourceRoot = path.join(projectRoot, "node_modules", "codemirror");
const sourceModes = path.join(sourceRoot, "mode");
const vendorRoot = path.join(projectRoot, "renderer", "vendor", "codemirror");
const targetModes = path.join(vendorRoot, "mode");

if (!fs.existsSync(sourceModes)) {
  console.error("node_modules/codemirror is missing. Run npm install first.");
  process.exit(1);
}

fs.mkdirSync(targetModes, { recursive: true });
fs.mkdirSync(path.join(vendorRoot, "addon"), { recursive: true });

// Core + addons the editor and the sandbox rely on.
for (const [from, to] of [
  ["lib/codemirror.js", "codemirror.js"],
  ["lib/codemirror.css", "codemirror.css"],
  ["addon/edit/matchbrackets.js", "addon/matchbrackets.js"],
  ["addon/edit/closebrackets.js", "addon/closebrackets.js"],
  ["addon/edit/closetag.js", "addon/closetag.js"],
  ["addon/selection/active-line.js", "addon/active-line.js"],
  ["addon/mode/simple.js", "addon/simple.js"],
]) {
  fs.copyFileSync(path.join(sourceRoot, from), path.join(vendorRoot, to));
}
fs.copyFileSync(path.join(sourceRoot, "LICENSE"), path.join(vendorRoot, "LICENSE"));

const dirs = fs
  .readdirSync(sourceModes, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

const missing = [];
let copied = 0;
for (const name of dirs) {
  const file = path.join(sourceModes, name, `${name}.js`);
  if (!fs.existsSync(file)) {
    missing.push(name);
    continue;
  }
  fs.copyFileSync(file, path.join(targetModes, `${name}.js`));
  copied += 1;
}
const modeFiles = fs.readdirSync(targetModes).filter((file) => file.endsWith(".js")).sort();

// CodeMirror's advertised language list, evaluated as the browser would build it.
const metaSource = fs.readFileSync(path.join(sourceModes, "meta.js"), "utf8");
const metaSandbox = { CodeMirror: { modeInfo: [] }, window: {}, navigator: { userAgent: "" } };
metaSandbox.globalThis = metaSandbox;
vm.createContext(metaSandbox);
vm.runInContext(metaSource, metaSandbox, { filename: "meta.js" });
const meta = metaSandbox.CodeMirror.modeInfo ?? [];

const { byFile, errors } = loadModes({
  modeDir: targetModes,
  files: modeFiles,
  preamble: [path.join(vendorRoot, "addon", "simple.js")],
});

// RegExp values come from inside the VM, so instanceof against this realm is
// false; identify them structurally instead.
function asPattern(value) {
  if (!value) return null;
  if (Object.prototype.toString.call(value) !== "[object RegExp]") return null;
  return { source: value.source, flags: value.flags };
}

const table = [];
const dropped = [];
for (const entry of meta) {
  const registrations = byFile.get(`${entry.mode}.js`);
  const registered = (registrations?.mimes ?? []).filter((mime) => mime && mime !== "null");
  // The editor's mode option also accepts a registered mode name, so a package
  // that defines a mode without a MIME is still usable.
  const usable = registered.length ? registered : (registrations?.modes ?? []).filter(Boolean);
  if (!usable.length) {
    dropped.push(`${entry.name} (${entry.mode})`);
    continue;
  }
  const pattern = asPattern(entry.file);
  table.push({
    name: entry.name,
    mode: entry.mode,
    mimes: usable,
    ext: entry.ext ? [...entry.ext] : [],
    file: pattern,
  });
}

if (!table.length) {
  console.error("No language registered any MIME; refusing to write an empty table.");
  process.exit(1);
}

fs.writeFileSync(path.join(vendorRoot, "mode-info.json"), `${JSON.stringify(table)}\n`, "utf8");
fs.writeFileSync(
  path.join(vendorRoot, "VENDOR.md"),
  [
    "# Vendored CodeMirror",
    "",
    "- Package: `codemirror@5.65.16` (MIT), copied unmodified from npm.",
    "- `codemirror.js`, `codemirror.css`, `addon/*`, `mode/*`: package files.",
    "- `mode-info.json`: generated by `scripts/build-modes.mjs` by executing the mode",
    "  packages and recording the MIME types they actually register.",
    "",
    `Languages in the table: ${table.length}. Mode packages copied: ${copied}.`,
    `Dropped (registered no MIME): ${dropped.length ? dropped.join(", ") : "none"}.`,
    "",
    "Do not edit these by hand; rerun the script instead.",
    "",
  ].join("\n"),
  "utf8",
);

console.log(`copied ${copied} mode packages`);
console.log(`languages in table: ${table.length}`);
if (dropped.length) console.log(`dropped (no MIME registered): ${dropped.join(", ")}`);
if (errors.length) console.log(`mode load errors: ${errors.map((error) => error.file).join(", ")}`);
if (missing.length) console.log(`skipped (no same-named entry point): ${missing.join(", ")}`);
console.log(`sample: ${table.slice(0, 10).map((entry) => `${entry.name} → ${entry.mimes[0]}`).join(", ")}`);
